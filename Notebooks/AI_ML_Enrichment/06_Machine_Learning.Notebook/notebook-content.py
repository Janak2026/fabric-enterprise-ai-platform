# # Step 3: Create Customer Feature Table
# 
# ## Overview
# 
# This step creates the **Machine_Learning_feature_customer** table.
# 
# The table contains one record per customer and includes engineered features derived from historical purchasing behaviour, payment patterns, delivery performance, and customer satisfaction.
# 
# These features will serve as reusable inputs for multiple machine learning models, including customer churn prediction, customer segmentation, recommendation systems, and customer lifetime value analysis.
# 
# ---
# 
# ## Output Table
# 
# - Machine_Learning_feature_customer
# 
# ## Grain
# 
# - One row per customer
# 
# ## Primary Key
# 
# - Customer_SK

# CELL ********************

# Cell 5:
# ============================================================
# Create Machine_Learning_feature_customer
# ============================================================

Machine_Learning_feature_customer = (

    Business_Models_fact_sales

    .groupBy("Customer_SK")

    .agg(

        # Customer Activity
        countDistinct("Order_ID").alias("Total_Orders"),
        count("Order_Item_ID").alias("Total_Items_Purchased"),
        round(sum("Total_Item_Value"), 2).alias("Total_Spent"),
        round(avg("Total_Item_Value"), 2).alias("Average_Order_Value"),

        # Payment Behaviour
        round(avg("Payment_Value"), 2).alias("Average_Payment_Value"),
        round(avg("Payment_Installments"), 2).alias("Average_Installments"),
        concat_ws(", ", collect_set("Payment_Type")).alias("Preferred_Payment_Type"),

        # Delivery Behaviour
        round(avg("Delivery_Days"), 2).alias("Average_Delivery_Days"),
        round(avg("Delivery_Delay_Days"), 2).alias("Average_Delivery_Delay"),

        round(
            avg(
                when(col("Delivery_Performance") == "On Time", 1)
                .otherwise(0)
            ) * 100,
            2
        ).alias("On_Time_Delivery_Rate"),

        # Customer Satisfaction
        round(avg("Review_Score"), 2).alias("Average_Review_Score"),

        sum(
            when(col("Review_Score") <= 2, 1)
            .otherwise(0)
        ).alias("Low_Rating_Count"),

        sum(
            when(col("Review_Score") >= 4, 1)
            .otherwise(0)
        ).alias("High_Rating_Count"),

        # Purchase Behaviour
        min("Order_Purchase_Timestamp").alias("First_Purchase_Date"),
        max("Order_Purchase_Timestamp").alias("Last_Purchase_Date")

    )

    .withColumn(
        "Customer_Lifetime_Days",
        datediff(
            col("Last_Purchase_Date"),
            col("First_Purchase_Date")
        )
    )

    .withColumn(
        "Created_Timestamp",
        current_timestamp()
    )

    .withColumn(
        "Modified_Timestamp",
        current_timestamp()
    )

)

