from pyspark.ml.feature import VectorAssembler
from pyspark.sql.functions import (
    col,
    abs,
    current_timestamp
)

# ------------------------------------------------------------
# Read Sales Feature Table
# ------------------------------------------------------------

sales_df = spark.table(
    "Machine_Learning_feature_sales"
)

# ------------------------------------------------------------
# Create Feature Vector
# ------------------------------------------------------------

feature_columns = [

    "Total_Orders",
    "Total_Items_Sold",
    "Average_Order_Value",
    "Average_Selling_Price",
    "Average_Freight_Cost",
    "Average_Delivery_Days",
    "Average_Delivery_Delay",
    "On_Time_Delivery_Rate",
    "Average_Review_Score",
    "Unique_Customers",
    "Unique_Products",
    "Unique_Sellers"

]

assembler = VectorAssembler(
    inputCols=feature_columns,
    outputCol="features",
    handleInvalid="skip"
)

sales_prediction_df = assembler.transform(sales_df)

# ------------------------------------------------------------
# Generate Predictions
# ------------------------------------------------------------

Machine_Learning_prediction_sales = (
    rf_model
    .transform(sales_prediction_df)
    .select(
        "Calendar_SK",
        col("Total_Revenue").alias("Actual_Revenue"),
        col("prediction").alias("Predicted_Revenue")
    )
    .withColumn(
        "Prediction_Error",
        abs(
            col("Actual_Revenue") -
            col("Predicted_Revenue")
        )
    )
    .withColumn(
        "Prediction_Timestamp",
        current_timestamp()
    )
)

# ------------------------------------------------------------
# Save Prediction Table
# ------------------------------------------------------------

Machine_Learning_prediction_sales.write \
    .format("delta") \
    .mode("overwrite") \
    .saveAsTable("Machine_Learning_prediction_sales")

print("=" * 80)
print("Prediction Table Created Successfully")
print("=" * 80)

print("Table Name : Machine_Learning_prediction_sales")

